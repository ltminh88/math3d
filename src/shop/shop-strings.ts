export type ShopKey = Parameters<typeof raw>[0];

/** Shop string; `{guide}` is the guide's name from the common strings. */
export const tshop = (key: ShopKey, params?: Params): string =>
  raw(key, { guide: tc('guideName'), ...params });

/** Display name of a catalog item (its id is also its string key). */
export const cosmeticName = (id: string): string => tshop(id as ShopKey);
