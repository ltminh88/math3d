const ms = defineStrings('measurement', { vi, en });

/** Renders a measurement prompt; shared labels (units, numbers, letters) fall back to geometry. */
export const renderMeasurementPrompt = (prompt: PromptRef): string =>
  prompt.key in vi ? renderPromptWith(ms as Translator, prompt) : renderGeometryPrompt(prompt);
