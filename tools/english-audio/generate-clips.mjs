// Deterministic offline clip generator for English Island audio (Phase 2C).
//
// Pipeline: items.json (from collect-items.ts) -> Kokoro TTS (voice af_heart,
// speed 0.9) -> WAV scratch -> ffmpeg-normalize (RMS -20 dBFS) -> ffmpeg
// (trim silence, alimiter, mono 24 kHz, libmp3lame 40k) -> public/english-audio.
// The generator is idempotent: a clip is skipped when its mp3 exists and the
// stored text hash matches; a second run changes no file.
//
// Pure functions are unit-tested in generate-clips.test.ts. The runner at the
// bottom shells out to the Kokoro venv + ffmpeg; it never runs on import.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const VOICE = 'af_heart';
export const SPEED = 0.9;
export const SAMPLE_RATE = 24000;
export const AUDIO_URL_PREFIX = '/english-audio';

/** Letter name spellings: the TTS must hear "bee", never a bare "b". */
export const LETTER_NAMES = {
  a: 'ay',
  b: 'bee',
  c: 'cee',
  d: 'dee',
  e: 'ee',
  f: 'ef',
  g: 'gee',
  h: 'aych',
  i: 'eye',
  j: 'jay',
  k: 'kay',
  l: 'el',
  m: 'em',
  n: 'en',
  o: 'oh',
  p: 'pee',
  q: 'cue',
  r: 'ar',
  s: 'ess',
  t: 'tee',
  u: 'you',
  v: 'vee',
  w: 'double-you',
  x: 'ex',
  y: 'why',
  z: 'zee',
};

/** The fixed step-1 seed list (12 words + 5 letters + 4 sentences). */
export const SEED_TEXTS = JSON.parse(readFileSync(new URL('./seed.json', import.meta.url), 'utf8'));

/** File name for a clip id (the map value is `${AUDIO_URL_PREFIX}/${id}.mp3`). */
export function clipIdFor(item) {
  if (item.kind === 'letter') return `letter-${item.text}`;
  return item.text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** What Kokoro hears: words get a trailing period (bare short inputs glitch),
 * letters are spelled phonetically, sentences keep their punctuation. */
export function ttsTextFor(item) {
  if (item.kind === 'letter') return `${LETTER_NAMES[item.text]}.`;
  return /[.!?]$/.test(item.text) ? item.text : `${item.text}.`;
}

/** Short stable hash of the TTS input; a text change changes the hash. */
export function textHash(ttsText) {
  return createHash('sha256').update(ttsText, 'utf8').digest('hex').slice(0, 12);
}

/**
 * Decide per item: skip when the manifest records the same hash AND the mp3
 * is on disk; generate otherwise (new, changed text, or missing file).
 */
export function planClips(items, manifest, outDir) {
  return items.map((item) => {
    const id = clipIdFor(item);
    const hash = textHash(ttsTextFor(item));
    const stored = manifest.clips[id];
    const action =
      stored !== undefined && stored.hash === hash && existsSync(join(outDir, `${id}.mp3`))
        ? 'skip'
        : 'generate';
    return { ...item, id, hash, action };
  });
}

/**
 * The audio map the 3B speaker reads (`englishClipUrl`): exact spoken text
 * -> mp3 URL. Only clips that exist on disk are listed.
 */
export function emitAudioMap(entries) {
  // Biome drops quotes on identifier keys, so emit them bare; keep quotes
  // only for keys with spaces or other non-identifier characters.
  const lines = entries.map((e) => {
    const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(e.text) ? e.text : `'${e.text}'`;
    return `  ${key}: '${AUDIO_URL_PREFIX}/${e.id}.mp3',`;
  });
  return `// Pre-generated audio clips for English words/sentences (Phase 2C).
// Generated by tools/english-audio/generate-clips.mjs — do not edit by hand.
// Voice: Kokoro ${VOICE}, speed ${SPEED}. Re-run the generator to add clips.
export const ENGLISH_AUDIO_CLIPS: Readonly<Record<string, string>> = {
${lines.join('\n')}
};

/** Clip URL for the exact spoken text, or null when 2C has not provided one. */
export function englishClipUrl(text: string): string | null {
  return ENGLISH_AUDIO_CLIPS[text] ?? null;
}
`;
}

/** Credits for the committed clips: engine, voice, version, license. */
export function emitCredits({ kokoroVersion, speed }) {
  return `# English audio credits

Clips in this folder are pre-generated with **Kokoro-82M** (voice \`af_heart\`,
speed ${speed}), engine version \`${kokoroVersion}\`.

- Kokoro-82M weights and code: Apache License 2.0 (Apache-2.0)
  (https://huggingface.co/hexgrad/Kokoro-82M).
- Synthesised audio carries no additional restriction from the engine license.
- Fallback engine (only if Kokoro output is unusable for a clip):
  Piper \`en_US-ljspeech-high\`, public domain dataset.
- Generator: \`tools/english-audio/generate-clips.mjs\` (deterministic;
  re-running it regenerates only clips whose text changed).
`;
}

// --- Runner (only when executed, never on import) ---------------------------

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function run(cmd, args) {
  execFileSync(cmd, [...args], { stdio: 'inherit' });
}

/**
 * ffmpeg chain from the TTS research report: trim silence both ends (keeping
 * 30 ms leading / 80 ms trailing), limiter at ~-1 dBFS, mono 24 kHz,
 * libmp3lame 40k CBR, no metadata (Safari duration quirks on tiny files).
 */
function toMp3(wavPath, mp3Path) {
  const filter = [
    'silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.03',
    'areverse',
    'silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08',
    'areverse',
    'volume=0dB,alimiter=limit=0.89',
  ].join(',');
  run('ffmpeg', [
    '-y',
    '-i',
    wavPath,
    '-af',
    filter,
    '-ac',
    '1',
    '-ar',
    String(SAMPLE_RATE),
    '-c:a',
    'libmp3lame',
    '-b:a',
    '40k',
    '-map_metadata',
    '-1',
    '-id3v2_version',
    '0',
    '-write_xing',
    '0',
    mp3Path,
  ]);
}

function parseArgs(argv) {
  return {
    seed: argv.includes('--seed'),
    venv:
      argv.find((a) => a.startsWith('--venv='))?.slice('--venv='.length) ??
      join(process.env.HOME ?? '', 'workspace', 'kokoro-venv'),
  };
}

function main() {
  const { seed, venv } = parseArgs(process.argv.slice(2));
  const itemsPath = join(HERE, 'items.json');
  const manifestPath = join(HERE, 'clips.json');
  const outDir = join(REPO, 'public', 'english-audio');
  const wavDir = join(HERE, 'wav');
  const normDir = join(HERE, 'wav-norm');
  const audioMapPath = join(REPO, 'src', 'english', 'content', 'audio-map.ts');
  const creditsPath = join(outDir, 'AUDIO-CREDITS.md');

  const allItems = readJson(itemsPath);
  const items = seed ? allItems.filter((i) => i.seed) : allItems;
  const manifest = existsSync(manifestPath) ? readJson(manifestPath) : { clips: {} };
  const plan = planClips(items, manifest, outDir);
  const toGenerate = plan.filter((p) => p.action === 'generate');
  console.log(
    `plan: ${plan.length} clips (${toGenerate.length} to generate, ${plan.length - toGenerate.length} skipped)`,
  );
  if (toGenerate.length === 0) {
    console.log('nothing to generate — second run is a no-op');
    return;
  }

  mkdirSync(wavDir, { recursive: true });
  mkdirSync(normDir, { recursive: true });
  mkdirSync(outDir, { recursive: true });

  // 1. Synthesise WAVs with Kokoro (venv python).
  const ttsInput = join(wavDir, 'tts-items.json');
  writeFileSync(
    ttsInput,
    JSON.stringify(
      toGenerate.map((p) => ({ id: p.id, tts: ttsTextFor(p) })),
      null,
      2,
    ),
    'utf8',
  );
  run(join(venv, 'bin', 'python'), [
    join(HERE, 'synthesize.py'),
    '--items',
    ttsInput,
    '--out',
    wavDir,
  ]);

  // 2. RMS-normalise the WAVs (per-file -20 dBFS), then convert each to MP3.
  const wavs = toGenerate.map((p) => join(wavDir, `${p.id}.wav`));
  run(join(venv, 'bin', 'ffmpeg-normalize'), [
    ...wavs,
    '-nt',
    'rms',
    '-t',
    '-20',
    '-ext',
    'wav',
    '-of',
    normDir,
  ]);
  for (const p of toGenerate) {
    toMp3(join(normDir, `${p.id}.wav`), join(outDir, `${p.id}.mp3`));
  }

  // 3. Update the manifest + emit the audio map and credits.
  const clips = { ...manifest.clips };
  for (const p of plan) clips[p.id] = { text: p.text, hash: p.hash };
  const nextManifest = { version: 1, voice: VOICE, speed: SPEED, clips };
  writeFileSync(manifestPath, `${JSON.stringify(nextManifest, null, 2)}\n`, 'utf8');
  const entries = Object.keys(clips)
    .sort()
    .map((id) => ({ text: clips[id].text, id }))
    .filter((e) => existsSync(join(outDir, `${e.id}.mp3`)));
  writeFileSync(audioMapPath, emitAudioMap(entries), 'utf8');
  const kokoroVersion =
    execFileSync(join(venv, 'bin', 'pip'), ['show', 'kokoro'], { encoding: 'utf8' })
      .split('\n')
      .find((l) => l.startsWith('Version:'))
      ?.slice('Version:'.length)
      .trim() ?? 'unknown';
  writeFileSync(creditsPath, emitCredits({ kokoroVersion, speed: SPEED }), 'utf8');
  console.log(`done: ${toGenerate.length} clips generated, map + credits written`);
}

if (process.argv[1] !== undefined && import.meta.url === `file://${process.argv[1]}`) {
  main();
}
