#!/usr/bin/env node
// Slices the closure-free functions of the ORIGINAL bundle (prettier-formatted, otherwise
// untouched) into a CommonJS harness so golden traces come from the real shipped code.
// Usage: node tools/recovery/golden/extract-original-pure-functions.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../..');
const sourcePath = join(root, 'recovered/formatted/game-app-section.js');
const outPath = join(here, 'original-pure-harness.cjs');

// [firstLine, lastLine, expected text at first line, expected text at last line] (1-based)
const RANGES = [
  [1, 154, 'const Ha = [2, 3, 4, 5, 6, 7, 8, 9, 10],', 'Ps = (i) => Dt.find((e) => e.id === i);'],
  [1256, 1389, 'const Ga = () => ({', '}'],
  [1674, 1722, "const sg = '#194f42';", '}'],
];
// The scatter LCG is an inline closure (line 744); lift its exact expression.
const LCG_LINE = 744;
const LCG_TEXT = 'const t = () => ((e = (e * 16807) % 2147483647), (e - 1) / 2147483646),';

// Exported names; generate-golden-traces.mjs asserts their arity when it loads the harness.
const EXPORTS = [
  ...['Ha', 'Kl', 'yt', 'Sa', 'Qe', 'kr', 'fe', 'Dt', 'Wr', 'Xm', 'Di', 'Ps'],
  ...['Ga', 'Gn', 'Ym', 'jm', 'll', 'Jm', 'Qm', 'eg', 'tg', 'ag', 'og', 'originalLcg'],
];

const lines = readFileSync(sourcePath, 'utf8').split('\n');
const take = (first, last, head, tail) => {
  const got = [lines[first - 1]?.trim(), lines[last - 1]?.trim()];
  if (got[0] !== head || got[1] !== tail) {
    throw new Error(`range ${first}-${last} drifted: got ${JSON.stringify(got)}`);
  }
  return lines.slice(first - 1, last).join('\n');
};

if (lines[LCG_LINE - 1]?.trim() !== LCG_TEXT) throw new Error(`LCG line ${LCG_LINE} drifted`);
const lcgExpr = LCG_TEXT.replace('const t = ', '').replace(/,$/, '');

const sourceHash = createHash('sha256').update(lines.join('\n')).digest('hex');
const body = [
  '// GENERATED by extract-original-pure-functions.mjs — do not edit.',
  `// source: ${relative(root, sourcePath)} sha256=${sourceHash}`,
  `// ranges: ${RANGES.map(([a, b]) => `${a}-${b}`).join(', ')}; lcg line ${LCG_LINE}`,
  '/* eslint-disable */',
  ...RANGES.map((r) => take(...r)),
  `function originalLcg(seed) {\n  let e = seed;\n  return ${lcgExpr};\n}`,
  `module.exports = { ${EXPORTS.join(', ')} };`,
  '',
].join('\n');

writeFileSync(outPath, body);
console.log(`wrote ${relative(root, outPath)} (${body.length} bytes)`);
